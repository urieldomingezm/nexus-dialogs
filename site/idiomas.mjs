// Nombre del idioma en que está una página, dicho en cada idioma (para «Esta página está solo en español»).
const EN_IDIOMA = {
  es: { es: 'español', en: 'inglés', pt: 'portugués', fr: 'francés' },
  en: { es: 'Spanish', en: 'English', pt: 'Portuguese', fr: 'French' },
  pt: { es: 'espanhol', en: 'inglês', pt: 'português', fr: 'francês' },
  fr: { es: 'espagnol', en: 'anglais', pt: 'portugais', fr: 'français' },
}

export const ui = (lang) => UI[lang] ?? UI.es
export const grupos = (lang) => MENU[lang]?.grupos ?? MENU.es.grupos
/** [texto del menú, descripción, título/encabezado] de una página en un idioma. */
export const pagina = (lang, id) => {
  const [t, d, h] = MENU[lang]?.p[id] ?? MENU.es.p[id]
  return { texto: t, desc: d, titulo: h ?? t }
}
export const avisoDe = (lang, enQue) => ui(lang).aviso(EN_IDIOMA[lang][enQue])

/** Idioma de una página según su ruta: `/en/soporte.html` → `en`; lo demás, español. */
export const idiomaDeRuta = (ruta) => {
  const m = String(ruta).match(/(?:^|\/)(en|pt|fr)\/[^/]*$/)
  return m ? m[1] : 'es'
}
